/**
 * Get all system fields for a given entity scope
 * @param entityScope - Filter by entity type (contact, opportunity, etc.)
 * @returns Array of system field definitions
 */
export function getSystemFields(entityScope?: EntityScope): SystemFieldDefinition[] {
  if (entityScope === 'contact') {
    return CONTACT_SYSTEM_FIELDS;
  }

  // Future: Add other entity types
  // if (entityScope === 'opportunity') return OPPORTUNITY_SYSTEM_FIELDS;
  // if (entityScope === 'company') return COMPANY_SYSTEM_FIELDS;
  // if (entityScope === 'deal') return DEAL_SYSTEM_FIELDS;

  // If no entityScope provided, return all system fields
  if (!entityScope) {
    return [...CONTACT_SYSTEM_FIELDS];
  }

  return [];
}

/**
 * Check if a field name is reserved as a system field
 * @param name - Field name to check
 * @param entityScope - Entity scope to check within
 * @returns True if the name is reserved
 */
export function isSystemFieldName(name: string, entityScope: EntityScope): boolean {
  return getSystemFields(entityScope).some((f) => f.name === name);
}

/**
 * Get a specific system field by name
 * @param name - Field name
 * @param entityScope - Entity scope
 * @returns System field definition or undefined
 */
export function getSystemField(
  name: string,
  entityScope: EntityScope
): SystemFieldDefinition | undefined {
  return getSystemFields(entityScope).find((f) => f.name === name);
}

/**
 * Get all reserved field names for an entity scope
 * @param entityScope - Entity scope
 * @returns Array of reserved field names
 */
export function getReservedFieldNames(entityScope: EntityScope): string[] {
  return getSystemFields(entityScope).map((f) => f.name);
}
