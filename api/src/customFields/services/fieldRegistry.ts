/**
 * Field Registry
 * Central registry for all system-defined fields across entities
 * System fields are code-defined and not stored in Firestore
 */

import { FieldType, EntityScope, FieldValidation } from '../types';

export interface SystemFieldDefinition {
  name: string;
  displayName: string;
  type: FieldType;
  entityScope: EntityScope;
  group?: string;
  validation?: Partial<FieldValidation>;
  order: number;
  description?: string;
  // Metadata flags for special handling
  isAlwaysPresent?: boolean;      // Always exists on entity (id, tenant_id, created_at)
  isAutoGenerated?: boolean;      // Auto-generated/derived (firstName from name)
  isMergedFromExternal?: boolean; // Merged from another collection (phoneNumber)
  isInternal?: boolean;           // Internal fields not meant for user selection (id, tenant_id, created_at, updated_at)
  hideFromUI?: boolean;           // Hide from UI contact detail/conversation pages (but still available in automations)
}

